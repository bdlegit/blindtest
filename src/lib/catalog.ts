/**
 * Catalogue intégré : les catégories du mode « Blind test à thème ».
 *
 * Chaque morceau est décrit par la RÉPONSE attendue (titre + artiste, avec variantes).
 * L'extrait audio et la pochette sont cherchés à la volée chez le fournisseur audio (Deezer).
 * Pour les musiques de films, séries, dessins animés, jeux vidéo et génériques, le « titre »
 * à trouver est le nom de l'œuvre et l'« artiste » le compositeur ou l'interprète.
 */

export type SeedTrack = {
  artist: string;
  title: string;
  /** requête de recherche si différente de « artiste titre » */
  q?: string;
  ta?: string[]; // variantes du titre
  aa?: string[]; // variantes de l'artiste
  /** œuvres : mots-clés attendus dans le titre/l'album du résultat (par défaut : le titre) */
  m?: string[];
};

export type Category = {
  id: string;
  label: string;
  emoji: string;
  /** dégradé de la carte */
  gradient: [string, string];
  /** « titre » désigne l'œuvre (film, jeu…) plutôt que la chanson */
  workTitle?: boolean;
  tracks: SeedTrack[];
};

const t = (artist: string, title: string, extra: Omit<SeedTrack, "artist" | "title"> = {}): SeedTrack => ({
  artist,
  title,
  ...extra,
});

